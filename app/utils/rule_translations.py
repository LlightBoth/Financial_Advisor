def localize_rule(rule_obj_or_dict: Any, lang: Optional[str] = None) -> Dict[str, Any]:
    """
    Normalizes and localizes any Rule object or dictionary into the unified
    structure consumed by templates. Handles both English and Khmer.
    """
    if lang is None:
        lang = get_locale()

    if isinstance(rule_obj_or_dict, dict):
        raw_id = rule_obj_or_dict.get("id") or rule_obj_or_dict.get("rule_id", 1)
        raw_name = rule_obj_or_dict.get("name") or "Financial Rule"
        certainty = float(rule_obj_or_dict.get("certainty", 0.85) or 0.85)
        raw_conclusion = rule_obj_or_dict.get("conclusion") or ""
        raw_conclusion_km = rule_obj_or_dict.get("conclusion_km")
        raw_advice = rule_obj_or_dict.get("advice") or []
        raw_advice_km = rule_obj_or_dict.get("advice_km")
        category = rule_obj_or_dict.get("category", "")
        priority = rule_obj_or_dict.get("priority", 0)
    else:
        raw_id = getattr(rule_obj_or_dict, "id", None) or getattr(rule_obj_or_dict, "rule_id", 1)
        raw_name = getattr(rule_obj_or_dict, "name", None) or "Financial Rule"
        certainty = float(getattr(rule_obj_or_dict, "certainty", 0.85) or 0.85)
        raw_conclusion = getattr(rule_obj_or_dict, "conclusion_en", None) or getattr(rule_obj_or_dict, "conclusion", "")
        raw_conclusion_km = getattr(rule_obj_or_dict, "conclusion_km", None)
        raw_advice = getattr(rule_obj_or_dict, "advice_en", None) or getattr(rule_obj_or_dict, "advice", [])
        raw_advice_km = getattr(rule_obj_or_dict, "advice_km", None)
        category = getattr(rule_obj_or_dict, "category", "")
        priority = getattr(rule_obj_or_dict, "priority", 0)

    # Normalize advice to list of strings
    def _normalize_advice(adv: Any) -> List[str]:
        if isinstance(adv, list):
            return [str(x).strip() for x in adv if str(x).strip()]
        if isinstance(adv, str) and adv.strip():
            parts = [p.strip() for p in adv.split(".") if p.strip()]
            return [p + "." for p in parts] if len(parts) > 1 else [adv.strip()]
        return []

    advice_en_list = _normalize_advice(raw_advice)

    if lang == "km":
        # Localized name
        name_km = RULE_NAMES_KM.get(raw_name) or raw_name

        # Localized conclusion
        conclusion_km = raw_conclusion_km or RULE_CONCLUSIONS_KM.get(raw_conclusion) or raw_conclusion

        # Localized advice
        if raw_advice_km:
            advice_km_list = _normalize_advice(raw_advice_km)
        elif raw_conclusion in RULE_ADVICE_KM:
            advice_km_list = _normalize_advice(RULE_ADVICE_KM[raw_conclusion])
        elif raw_name in RULE_ADVICE_KM:
            advice_km_list = _normalize_advice(RULE_ADVICE_KM[raw_name])
        else:
            advice_km_list = advice_en_list

        return {
            "id": raw_id,
            "name": name_km,
            "certainty": certainty,
            "conclusion": conclusion_km,
            "advice": advice_km_list,
            "category": category,
            "priority": priority,
        }

    # English default
    return {
        "id": raw_id,
        "name": raw_name,
        "certainty": certainty,
        "conclusion": raw_conclusion,
        "advice": advice_en_list,
        "category": category,
        "priority": priority,
    }
